"""
2352. 같은 행과 열 쌍의 개수

0부터 인덱스가 시작하는 n × n 정수 행렬 grid가 주어진다.

행 ri와 열 cj의 내용이 서로 같은 모든 쌍 (ri, cj)의 개수를 반환하라.

행과 열에 들어 있는 원소가 순서까지 완전히 같을 때 두 배열이 같다고 판단한다.

예제 1
입력:
grid = [
    [3, 2, 1],
    [1, 7, 6],
    [2, 7, 7]
]

출력: 1

행들은 다음과 같다.

0번 행: [3, 2, 1]
1번 행: [1, 7, 6]
2번 행: [2, 7, 7]

열들은 다음과 같다.

0번 열: [3, 1, 2]
1번 열: [2, 7, 7]
2번 열: [1, 6, 7]

같은 행과 열은 다음 하나뿐이다.

(2번 행, 1번 열): [2, 7, 7]

따라서 1을 반환한다.

예제 2
입력:
grid = [
    [3, 1, 2, 2],
    [1, 4, 4, 5],
    [2, 4, 2, 2],
    [2, 4, 2, 2]
]

출력: 3

서로 같은 행과 열의 쌍은 다음 세 개다.

(0번 행, 0번 열): [3, 1, 2, 2]
(2번 행, 2번 열): [2, 4, 2, 2]
(3번 행, 2번 열): [2, 4, 2, 2]

여기서 2번 행과 3번 행은 내용이 서로 같다. 둘 다 2번 열과 일치하므로 각각 별도의 쌍으로 계산한다.

따라서 3을 반환한다.
"""

class Solution(object):
    def equalPairs(self, grid):
        """
        :type grid: List[List[int]]
        :rtype: int
        """
        row_count = {}
        answer = 0

        # 각 행을 튜플로 변환해 등장 횟수 저장 (리스트는 변경 가능해서 dict 키로 못 씀)
        for row in grid:
            row_tuple = tuple(row)
            row_count[row_tuple] = row_count.get(row_tuple, 0) + 1

        # zip(*grid)로 열을 하나씩 꺼내서, 같은 내용의 행이 몇 개였는지 더한다
        for column in zip(*grid):
            answer += row_count.get(tuple(column), 0)

        return answer